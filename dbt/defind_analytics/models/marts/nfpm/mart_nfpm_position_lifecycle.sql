WITH
liquidity_lifecycle AS (
    SELECT
        token_id,
        min(block_number)                                                       AS first_liquidity_event_block_number,
        min(block_time)                                                         AS first_liquidity_event_block_time,
        minIf(block_number, event_type = 'IncreaseLiquidity')                   AS first_increase_block_number,
        minIf(block_time, event_type = 'IncreaseLiquidity')                     AS first_increase_block_time,
        maxIf(block_number, event_type = 'IncreaseLiquidity')                   AS last_increase_block_number,
        maxIf(block_time, event_type = 'IncreaseLiquidity')                     AS last_increase_block_time,
        minIf(block_number, event_type = 'DecreaseLiquidity')                   AS first_decrease_block_number,
        minIf(block_time, event_type = 'DecreaseLiquidity')                     AS first_decrease_block_time,
        maxIf(block_number, event_type = 'DecreaseLiquidity')                   AS last_decrease_block_number,
        maxIf(block_time, event_type = 'DecreaseLiquidity')                     AS last_decrease_block_time
    FROM {{ ref('int_nfpm_position_liquidity_events') }}
    GROUP BY token_id
)

SELECT
    c.token_id,
    c.pool,
    c.tick_lower,
    c.tick_upper,
    c.range_width_ticks,
    c.initial_owner,
    c.current_owner,
    c.mint_tx_hash,
    c.mint_block_number,
    c.mint_block_time,
    c.transfer_count,
    c.burn_transfer_count,
    c.increase_count,
    c.decrease_count,
    c.collect_count,
    c.is_open,
    c.is_active,
    c.is_nft_burned,
    c.is_current_owner_burn_like,
    multiIf(
        c.is_nft_burned, 'burned',
        c.is_current_owner_burn_like, 'owner_burn_like',
        c.is_open, 'open',
        'closed_unburned'
    )                                                                         AS lifecycle_status,
    c.current_liquidity_raw,
    c.current_liquidity_share_of_initial,
    c.current_position_amount0,
    c.current_position_amount1,
    c.current_position_token0,
    c.total_deposit_amount0,
    c.total_deposit_amount1,
    c.total_withdraw_amount0,
    c.total_withdraw_amount1,
    c.total_collected_amount0,
    c.total_collected_amount1,
    c.total_principal_collected_amount0,
    c.total_principal_collected_amount1,
    c.total_fees_collected_amount0,
    c.total_fees_collected_amount1,
    c.first_secondary_transfer_block_number,
    c.first_secondary_transfer_block_time,
    c.last_secondary_transfer_block_number,
    c.last_secondary_transfer_block_time,
    c.burn_transfer_block_number,
    c.burn_transfer_block_time,
    c.distinct_to_address_count,
    ll.first_liquidity_event_block_number,
    ll.first_liquidity_event_block_time,
    ll.first_increase_block_number,
    ll.first_increase_block_time,
    ll.last_increase_block_number,
    ll.last_increase_block_time,
    ll.first_decrease_block_number,
    ll.first_decrease_block_time,
    ll.last_decrease_block_number,
    ll.last_decrease_block_time,
    c.first_collect_block_number,
    c.first_collect_block_time,
    c.last_collect_block_number,
    c.last_collect_block_time,
    c.last_position_activity_time,
    dateDiff('second', c.mint_block_time, c.last_position_activity_time)      AS observed_lifetime_seconds,
    if(c.first_collect_block_time IS NULL, NULL, dateDiff('second', c.mint_block_time, c.first_collect_block_time)) AS time_to_first_collect_seconds,
    if(c.is_open, NULL, dateDiff('second', c.mint_block_time, c.last_liquidity_event_block_time)) AS time_to_close_seconds,
    if(c.is_nft_burned, dateDiff('second', c.mint_block_time, c.burn_transfer_block_time), NULL) AS time_to_burn_seconds
FROM {{ ref('mart_nfpm_positions_current') }} c
LEFT JOIN liquidity_lifecycle ll ON c.token_id = ll.token_id
